const {chromium} = require(process.env.TEMP + '/furu-browser/node_modules/playwright');
const fs = require('node:fs');
const path = require('node:path');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
  const page = await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
  const errors = [];
  async function enter(label, value) {
    const field = page.getByRole('textbox', {name:label,exact:true});
    await field.click();
    await page.keyboard.press('Control+A');
    await page.keyboard.type(value, {delay:25});
    await page.keyboard.press('Tab');
    await page.waitForTimeout(150);
  }
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8080');
  await page.waitForTimeout(4000);
  await page.screenshot({path:'docs/validation/welcome-390.png'});
  // Enable Flutter's semantic DOM for browser-level interaction.
  await page.evaluate(() => document.querySelector('flt-semantics-placeholder')?.click());
  await page.waitForTimeout(600);
  const guestEntry = page.getByRole('button', {name:'Browse pets as a guest'});
  await guestEntry.click({timeout:15000});
  await page.waitForTimeout(1200);
  await page.screenshot({path:'docs/validation/home-390.png'});
  for (const width of [320,360,390,412,768]) {
    await page.setViewportSize({width,height:844});
    await page.waitForTimeout(300);
    await page.screenshot({path:`docs/validation/home-${width}.png`});
  }
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button', {name:/^Rescue/}).first().click();
  await page.waitForTimeout(500);
  await page.screenshot({path:'docs/validation/rescue-390.png'});
  await page.getByRole('button', {name:'Back',exact:true}).click();
  await page.waitForTimeout(400);
  await page.getByRole('tab', {name:/Discover/}).click();
  await page.waitForTimeout(500);
  await page.screenshot({path:'docs/validation/discover-390.png'});
  await page.getByRole('group', {name:/^Milo 2 years/}).click();
  await page.waitForTimeout(500);
  await page.screenshot({path:'docs/validation/pet-detail-390.png'});
  await page.getByRole('button', {name:'Apply for adoption'}).click();
  await page.waitForTimeout(500);
  await page.screenshot({path:'docs/validation/adoption-390.png'});
  await enter('Phone number', '09171234567');
  await page.getByRole('button', {name:'Continue',exact:true}).click();
  await page.waitForTimeout(400);
  await page.getByRole('button', {name:'Save & exit',exact:true}).click();
  await page.waitForTimeout(400);
  await page.getByRole('button', {name:'Back',exact:true}).click();
  await page.getByRole('tab', {name:'Profile',exact:true}).click();
  await page.waitForTimeout(400);
  await page.getByRole('button', {name:/^Rehome a pet/}).click();
  await page.waitForTimeout(400);
  await enter('Pet name', 'Poppy');
  await enter('Breed', 'Mixed breed');
  await enter('Age in months', '18');
  await page.getByRole('button', {name:'Species',exact:true}).click();
  await page.waitForTimeout(300);
  await page.getByRole('menuitem', {name:'Dog',exact:true}).click();
  await page.getByRole('button', {name:'Sex',exact:true}).click();
  await page.getByRole('menuitem', {name:'Female',exact:true}).click();
  await page.getByRole('button', {name:'Size',exact:true}).click();
  await page.getByRole('menuitem', {name:'Small',exact:true}).click();
  await page.getByRole('button', {name:'Continue',exact:true}).click();
  await page.waitForTimeout(400);
  const chooser = page.waitForEvent('filechooser');
  await page.getByRole('button', {name:'Choose a pet photo',exact:true}).click();
  await (await chooser).setFiles('assets/pets/milo.jpg');
  await page.waitForTimeout(700);
  await page.screenshot({path:'docs/validation/rehome-photo-390.png'});
  await page.getByRole('button', {name:'Continue',exact:true}).click();
  await page.waitForTimeout(400);
  const documentChooser = page.waitForEvent('filechooser');
  await page.getByRole('button', {name:'Choose a document',exact:true}).click();
  await (await documentChooser).setFiles('assets/pets/luna.jpg');
  await page.waitForTimeout(500);
  await page.screenshot({path:'docs/validation/rehome-health-390.png'});
  fs.writeFileSync(path.resolve('docs/validation/browser-result.json'), JSON.stringify({errors, widths:[320,360,390,412,768], checks:['welcome','navigation','rescue contacts','pet details','adoption contact keyboard entry','draft save and exit','rehoming dropdowns','photo picker','document picker'], url:page.url()},null,2));
  console.log(JSON.stringify({errors, buttons:await page.getByRole('button').allTextContents()}));
  await browser.close();
})();
